use anyhow::{Result, anyhow};
use rustls::pki_types::{CertificateDer, PrivateKeyDer};
use solana_sdk::{
    pubkey::Pubkey,
    signature::{Keypair, Signer},
};

const ED25519_PKCS8_PREFIX: [u8; 16] = [
    0x30, 0x2e, 0x02, 0x01, 0x00, 0x30, 0x05, 0x06, 0x03, 0x2b, 0x65, 0x70, 0x04, 0x22, 0x04, 0x20,
];

const CERT_PUBKEY_OFFSET: usize = 100;
const CERT_PUBKEY_LEN: usize = 32;

#[allow(dead_code)]
pub struct OverlayIdentity {
    pub cert: CertificateDer<'static>,
    pub key: PrivateKeyDer<'static>,
    pub pubkey: Pubkey,
}

impl OverlayIdentity {
    pub fn from_keypair(keypair: &Keypair) -> Result<Self> {
        let cert = identity_certificate(keypair);
        let key = identity_private_key(keypair)?;
        Ok(Self {
            cert,
            key,
            pubkey: keypair.pubkey(),
        })
    }
}

#[allow(dead_code)]
pub fn pubkey_from_certificate(cert: &CertificateDer<'_>) -> Option<Pubkey> {
    let end = CERT_PUBKEY_OFFSET.checked_add(CERT_PUBKEY_LEN)?;
    let raw = cert.as_ref().get(CERT_PUBKEY_OFFSET..end)?;
    Pubkey::try_from(raw).ok()
}

fn identity_private_key(keypair: &Keypair) -> Result<PrivateKeyDer<'static>> {
    let secret = keypair.secret_bytes();
    let mut key_pkcs8_der = Vec::with_capacity(ED25519_PKCS8_PREFIX.len() + secret.len());
    key_pkcs8_der.extend_from_slice(&ED25519_PKCS8_PREFIX);
    key_pkcs8_der.extend_from_slice(secret);
    PrivateKeyDer::try_from(key_pkcs8_der)
        .map_err(|e| anyhow!("failed to encode overlay Ed25519 identity key: {e}"))
}

