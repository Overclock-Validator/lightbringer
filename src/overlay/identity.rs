#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn certificate_roundtrips_solana_pubkey() {
        let keypair = Keypair::new();
        let identity = OverlayIdentity::from_keypair(&keypair).unwrap();
        assert_eq!(identity.pubkey, keypair.pubkey());
        assert_eq!(
            pubkey_from_certificate(&identity.cert),
            Some(keypair.pubkey())
        );
    }
}
